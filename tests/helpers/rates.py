"""Оракул ограничения скорости: что именно проверяется у `rate_limit` (A-FQ-12).

Лимитер с фиксированным окном отсчитывает окна от своего первого разрешения, а
не от целой секунды. Поэтому раскладка событий по целым секундам
(``Counter(int(at))``) ничего не доказывает: одно окно лимитера может попасть в
две соседние секунды, и тогда в одной целой секунде окажется до ``2 * limit``
событий, хотя лимитер не нарушен. Проверять нужно то, что ограничение
действительно означает:

* работа растянулась во времени — без лимитера все события пришли бы пачкой;
* ни в одной скользящей секунде не больше ``2 * limit`` событий — это предел
  фиксированного окна на границе двух окон.
"""

from __future__ import annotations

__all__ = ["max_in_window", "min_span", "span"]


def span(times: list[float]) -> float:
    """Длительность между первым и последним событием.

    Args:
        times: Моменты событий в секундах, в любом порядке.

    Returns:
        Разница между максимумом и минимумом; ``0.0`` для пустого списка.
    """
    if not times:
        return 0.0
    return max(times) - min(times)


def max_in_window(times: list[float], window: float = 1.0) -> int:
    """Наибольшее число событий в скользящем окне длиной ``window``.

    Окна берутся начиная с каждого события: любое окно с максимумом событий
    можно сдвинуть вправо до ближайшего события, не потеряв ни одного.

    Args:
        times: Моменты событий в секундах.
        window: Длина окна в секундах.

    Returns:
        Максимум событий, попавших в одно окно; ``0`` для пустого списка.
    """
    if not times:
        return 0
    return max(sum(start <= at < start + window for at in times) for start in times)


def min_span(count: int, limit: int) -> float:
    """Сколько времени минимум займут ``count`` событий при ``limit`` в секунду.

    Первое окно выпускает ``limit`` событий сразу, поэтому ждать приходится
    ``ceil(count / limit) - 1`` полных окон.

    Args:
        count: Сколько событий всего.
        limit: Разрешено событий в секунду.

    Returns:
        Минимальная длительность в секундах.
    """
    if count <= limit:
        return 0.0
    return float(-(-count // limit) - 1)
